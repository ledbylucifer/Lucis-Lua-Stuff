-- basicamente, as 4 chunks sao validas.

-- primeira parte:

a = 1
b = a*2
print(b) --> 2

-- segunda parte: 
c = 1;
d = c*2;
print(d) --> 2

-- terceira parte:

e = 1; f = e*2 --> o ';' é tipo uma separaçao por conta de oneliner. 
print(f) --> 2

-- terceira parte:

g = 1  h = g*2 --> feio, mas valido.
print(h) --> 2 

-- tem também como ter coisas sem "nada" usando o nil.

i = nil
print(i) --> nil, nil nao é um valor, é o equivalente de null. 


